/// This implementation is based on the [Twofish][spec] specification by
/// Bruce Schneier, et al., following the structure of the public domain
/// LibTom implementation.
///
/// [spec]: https://www.schneier.com/academic/twofish/
abstract class TwofishCore {
  /// Returns `a * b` in **GF(`2^8`)** with the primitive polynomial [p]
  static int _gfMult(int a, int b, int p) {
    int i, result = 0;
    for (i = 0; i < 8; ++i) {
      if (a & 1 != 0) {
        result ^= b;
      }
      a >>>= 1;
      b <<= 1;
      if (b & 0x100 != 0) {
        b ^= p;
      }
    }
    return result & 0xFF;
  }

  /// The h function of the spec for a byte [x] replicated on all four lanes,
  /// keyed by the even ([offset] = 0) or odd ([offset] = 1) key words.
  static int _h(int x, Uint8List key, int offset) {
    int y0 = x, y1 = x, y2 = x, y3 = x;
    final k = key.length >>> 3;
    if (k == 4) {
      y0 = _q1[y0] ^ key[4 * (6 + offset)];
      y1 = _q0[y1] ^ key[4 * (6 + offset) + 1];
      y2 = _q0[y2] ^ key[4 * (6 + offset) + 2];
      y3 = _q1[y3] ^ key[4 * (6 + offset) + 3];
    }
    if (k >= 3) {
      y0 = _q1[y0] ^ key[4 * (4 + offset)];
      y1 = _q1[y1] ^ key[4 * (4 + offset) + 1];
      y2 = _q0[y2] ^ key[4 * (4 + offset) + 2];
      y3 = _q0[y3] ^ key[4 * (4 + offset) + 3];
    }
    y0 = _q1[_q0[_q0[y0] ^ key[4 * (2 + offset)]] ^ key[4 * offset]];
    y1 = _q0[_q0[_q1[y1] ^ key[4 * (2 + offset) + 1]] ^ key[4 * offset + 1]];
    y2 = _q1[_q1[_q0[y2] ^ key[4 * (2 + offset) + 2]] ^ key[4 * offset + 2]];
    y3 = _q0[_q1[_q1[y3] ^ key[4 * (2 + offset) + 3]] ^ key[4 * offset + 3]];
    return _mds0[y0] ^ _mds1[y1] ^ _mds2[y2] ^ _mds3[y3];
  }

  /// Expands the [key] of 16, 24, or 32 bytes into the cipher state of 1064
  /// words: 40 round subkeys followed by the 4 x 256 key-dependent S-boxes
  /// composed with the MDS matrix.
  static Uint32List $expandKey(Uint8List key) {
    int i, j, z, a, b, t;
    final k = key.length >>> 3;
    final w = Uint32List(40 + 1024);

    // compute the RS-derived S-box key bytes
    final s = Uint8List(16);
    for (i = 0; i < k; ++i) {
      for (j = 0; j < 4; ++j) {
        for (z = 0; z < 8; ++z) {
          s[4 * i + j] ^= _gfMult(key[8 * i + z], _rs[8 * j + z], _rsPoly);
        }
      }
    }

    // compute the 40 round subkeys
    for (i = 0; i < 20; ++i) {
      a = _h((2 * i) & 0xFF, key, 0);
      b = _h((2 * i + 1) & 0xFF, key, 1);
      b = ((b << 8) & _mask32) | (b >>> 24);
      w[2 * i] = (a + b) & _mask32;
      t = (a + b + b) & _mask32;
      w[2 * i + 1] = ((t << 9) & _mask32) | (t >>> 23);
    }

    // compute the key-dependent S-boxes composed with the MDS matrix,
    // using the RS-derived key bytes in reverse order
    for (i = 0; i < 256; ++i) {
      if (k == 2) {
        a = _q1[_q0[_q0[i] ^ s[0]] ^ s[4]];
        b = _q0[_q0[_q1[i] ^ s[1]] ^ s[5]];
        z = _q1[_q1[_q0[i] ^ s[2]] ^ s[6]];
        t = _q0[_q1[_q1[i] ^ s[3]] ^ s[7]];
      } else if (k == 3) {
        a = _q1[_q0[_q0[_q1[i] ^ s[0]] ^ s[4]] ^ s[8]];
        b = _q0[_q0[_q1[_q1[i] ^ s[1]] ^ s[5]] ^ s[9]];
        z = _q1[_q1[_q0[_q0[i] ^ s[2]] ^ s[6]] ^ s[10]];
        t = _q0[_q1[_q1[_q0[i] ^ s[3]] ^ s[7]] ^ s[11]];
      } else {
        a = _q1[_q0[_q0[_q1[_q1[i] ^ s[0]] ^ s[4]] ^ s[8]] ^ s[12]];
        b = _q0[_q0[_q1[_q1[_q0[i] ^ s[1]] ^ s[5]] ^ s[9]] ^ s[13]];
        z = _q1[_q1[_q0[_q0[_q0[i] ^ s[2]] ^ s[6]] ^ s[10]] ^ s[14]];
        t = _q0[_q1[_q1[_q0[_q1[i] ^ s[3]] ^ s[7]] ^ s[11]] ^ s[15]];
      }
      w[40 + i] = _mds0[a];
      w[296 + i] = _mds1[b];
      w[552 + i] = _mds2[z];
      w[808 + i] = _mds3[t];
    }

    return w;
  }

  @pragma('vm:prefer-inline')
  @pragma('dart2js:tryInline')
  static int $swap32(int x) =>
      ((x << 24) & 0xff000000) ^
      ((x << 8) & 0x00ff0000) ^
      ((x >>> 8) & 0x0000ff00) ^
      ((x >>> 24) & 0x000000ff);

  /// Encrypts a 128-bit [block] of four little-endian 32-bit words in-place
  /// with the expanded state [w].
  static void $encrypt(Uint32List block, Uint32List w) {
    int i, j, t0, t1;
    int a = block[0] ^ w[0];
    int b = block[1] ^ w[1];
    int c = block[2] ^ w[2];
    int d = block[3] ^ w[3];

    j = 8;
    for (i = 0; i < 8; ++i) {
      t0 = w[40 + (a & 0xFF)] ^
          w[296 + ((a >>> 8) & 0xFF)] ^
          w[552 + ((a >>> 16) & 0xFF)] ^
          w[808 + (a >>> 24)];
      t1 = w[296 + (b & 0xFF)] ^
          w[552 + ((b >>> 8) & 0xFF)] ^
          w[808 + ((b >>> 16) & 0xFF)] ^
          w[40 + (b >>> 24)];
      c ^= (t0 + t1 + w[j++]) & _mask32;
      c = (c >>> 1) | ((c << 31) & _mask32);
      d = (((d << 1) & _mask32) | (d >>> 31)) ^
          ((t0 + t1 + t1 + w[j++]) & _mask32);

      t0 = w[40 + (c & 0xFF)] ^
          w[296 + ((c >>> 8) & 0xFF)] ^
          w[552 + ((c >>> 16) & 0xFF)] ^
          w[808 + (c >>> 24)];
      t1 = w[296 + (d & 0xFF)] ^
          w[552 + ((d >>> 8) & 0xFF)] ^
          w[808 + ((d >>> 16) & 0xFF)] ^
          w[40 + (d >>> 24)];
      a ^= (t0 + t1 + w[j++]) & _mask32;
      a = (a >>> 1) | ((a << 31) & _mask32);
      b = (((b << 1) & _mask32) | (b >>> 31)) ^
          ((t0 + t1 + t1 + w[j++]) & _mask32);
    }

    // output whitening with the final swap undone
    block[0] = c ^ w[4];
    block[1] = d ^ w[5];
    block[2] = a ^ w[6];
    block[3] = b ^ w[7];
  }

  /// Decrypts a 128-bit [block] of four little-endian 32-bit words in-place
  /// with the expanded state [w].
  static void $decrypt(Uint32List block, Uint32List w) {
    int i, j, t0, t1;
    int c = block[0] ^ w[4];
    int d = block[1] ^ w[5];
    int a = block[2] ^ w[6];
    int b = block[3] ^ w[7];

    j = 39;
    for (i = 0; i < 8; ++i) {
      t0 = w[40 + (c & 0xFF)] ^
          w[296 + ((c >>> 8) & 0xFF)] ^
          w[552 + ((c >>> 16) & 0xFF)] ^
          w[808 + (c >>> 24)];
      t1 = w[296 + (d & 0xFF)] ^
          w[552 + ((d >>> 8) & 0xFF)] ^
          w[808 + ((d >>> 16) & 0xFF)] ^
          w[40 + (d >>> 24)];
      b ^= (t0 + t1 + t1 + w[j--]) & _mask32;
      b = (b >>> 1) | ((b << 31) & _mask32);
      a = (((a << 1) & _mask32) | (a >>> 31)) ^ ((t0 + t1 + w[j--]) & _mask32);

      t0 = w[40 + (a & 0xFF)] ^
          w[296 + ((a >>> 8) & 0xFF)] ^
          w[552 + ((a >>> 16) & 0xFF)] ^
          w[808 + (a >>> 24)];
      t1 = w[296 + (b & 0xFF)] ^
          w[552 + ((b >>> 8) & 0xFF)] ^
          w[808 + ((b >>> 16) & 0xFF)] ^
          w[40 + (b >>> 24)];
      d ^= (t0 + t1 + t1 + w[j--]) & _mask32;
      d = (d >>> 1) | ((d << 31) & _mask32);
      c = (((c << 1) & _mask32) | (c >>> 31)) ^ ((t0 + t1 + w[j--]) & _mask32);
    }

    // undo the input whitening
    block[0] = a ^ w[0];
    block[1] = b ^ w[1];
    block[2] = c ^ w[2];
    block[3] = d ^ w[3];
  }
}

